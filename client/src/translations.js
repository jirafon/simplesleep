export const t = (key, language = defaultLanguage) => {
  const keys = key.split('.');
  let value = translations[language] || translations[defaultLanguage];
  
  for (const k of keys) {
    if (value && value[k] !== undefined) {
      value = value[k];
    } else {
      return key;
    }
  }
  
  return value;
}; 